/// `src/app_core/ids.rs` declares `RunId`/`ConversationId` through the
/// `string_uuid_id!` macro with a hand-written `Serialize` that emits a plain
/// string. There is no derive for `syn` to see, so the invocation itself is the
/// declaration this generator reads: delete the invocation and the TypeScript
/// alias disappears with it.
fn opaque_id_macro(item: &syn::ItemMacro) -> Option<String> {
    if !item.mac.path.is_ident("string_uuid_id") {
        return None;
    }
    let mut tokens = item.mac.tokens.clone().into_iter();
    match tokens.next() {
        Some(proc_macro2::TokenTree::Ident(ident)) => Some(ident.to_string()),
        _ => None,
    }
}
